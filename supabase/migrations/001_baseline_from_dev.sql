create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger training_resources_updated_at
  before update on public.training_resources
  for each row execute function public.set_updated_at();

-- Creates the profile (young person) or company row when someone signs up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
as $$
declare
  v_role text;
  v_first_name text;
begin
  v_role := coalesce(new.raw_user_meta_data->>'initial_role', 'talent');
  v_first_name := coalesce(new.raw_user_meta_data->>'full_name', 'New User');

  if v_role = 'company' then
    insert into public.companies (id, company_name)
    values (new.id, v_first_name);
  else
    insert into public.profiles (id, first_name)
    values (new.id, v_first_name);
  end if;

  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

